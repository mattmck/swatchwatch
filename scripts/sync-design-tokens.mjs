#!/usr/bin/env node
/**
 * Regenerate `packages/shared/src/constants/design-tokens.ts` from the web theme
 * (`apps/web/src/app/globals.css`), so web (Tailwind CSS variables) and mobile (React Native
 * hex colors) share one palette.
 *
 *   node scripts/sync-design-tokens.mjs          # rewrite the constants file
 *   node scripts/sync-design-tokens.mjs --check  # exit 1 when it is out of date (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildTokens, readWebTheme } from "./design-tokens-lib.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = resolve(root, "apps/web/src/app/globals.css");
const outPath = resolve(root, "packages/shared/src/constants/design-tokens.ts");

const tokens = buildTokens(readWebTheme(cssPath));

function objectLiteral(obj, indent = "  ") {
  return Object.entries(obj)
    .map(([key, value]) => `${indent}${key}: "${value}",`)
    .join("\n");
}

const source = `// Generated by scripts/sync-design-tokens.mjs from apps/web/src/app/globals.css. Do not edit:
// change the web theme and rerun \`npm run sync:design-tokens\` (CI runs it with --check).

/**
 * Semantic colors of the SwatchWatch theme as sRGB hex (\`#rrggbb\`, or \`#rrggbbaa\` when the
 * CSS value has alpha). The web defines them as \`oklch()\` CSS variables (shadcn/ui names);
 * React Native needs hex, so the mobile theme reads them from here.
 */
export interface ThemeColorTokens {
${Object.keys(tokens.light).map((key) => `  ${key}: string;`).join("\n")}
}

/** Brand palette (the \`--brand-*\` variables; equal to \`swatchWatchBrandPalette\`). */
export const BRAND_COLOR_TOKENS = {
${objectLiteral(tokens.brand)}
} as const;

/** Light theme (\`:root\`). */
export const LIGHT_THEME_COLORS: ThemeColorTokens = {
${objectLiteral(tokens.light)}
};

/** Dark theme (\`.dark\`). */
export const DARK_THEME_COLORS: ThemeColorTokens = {
${objectLiteral(tokens.dark)}
};

export type ThemeColorScheme = "light" | "dark";

export const THEME_COLORS: Record<ThemeColorScheme, ThemeColorTokens> = {
  light: LIGHT_THEME_COLORS,
  dark: DARK_THEME_COLORS,
};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing file is out of date
  }
  if (current !== source) {
    console.error(
      "packages/shared/src/constants/design-tokens.ts is out of date with apps/web/src/app/globals.css.\n" +
        "Run `npm run sync:design-tokens` and commit the result.",
    );
    process.exit(1);
  }
  console.log("Design tokens are in sync with the web theme.");
} else {
  writeFileSync(outPath, source);
  console.log(`Wrote ${outPath}`);
}
