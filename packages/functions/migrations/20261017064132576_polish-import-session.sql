-- CSV / spreadsheet import (issue #263, roadmap §3 Week 0 "CSV / spreadsheet import").
--
-- An import is three requests: upload (parse + fuzzy-match every row), review (the user
-- confirms ambiguous rows and picks create/skip for unmatched ones), commit (inventory
-- upserts). The parsed rows, their candidates and the user's decisions live here between
-- those requests (docs/schema.sql "CSV import sessions").
--
-- * Rows are user-owned: every API query filters on user_id (per-user isolation, #47).
-- * payload holds { delimiter, headers, headerRowIndex, mapping, rows[] } as JSON; it is
--   only ever read back whole by the owner, so there is nothing to normalize.
-- * Sessions expire after 24 h. Expired rows are invisible to the API immediately and are
--   deleted by the polish-import-session-cleanup timer (and on the owner's next upload).

BEGIN;

CREATE TABLE IF NOT EXISTS polish_import_session (
  import_session_id UUID PRIMARY KEY,           -- generated by the API (crypto.randomUUID)
  user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
  file_name TEXT,
  status TEXT NOT NULL DEFAULT 'review'
    CONSTRAINT chk_polish_import_session_status CHECK (status IN ('review', 'committed')),
  row_count INT NOT NULL DEFAULT 0,
  payload JSONB NOT NULL,
  result JSONB,                                 -- commit counts; NULL until committed
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  committed_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '24 hours'
);

CREATE INDEX IF NOT EXISTS idx_polish_import_session_user
  ON polish_import_session (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_polish_import_session_expires
  ON polish_import_session (expires_at);

COMMENT ON TABLE polish_import_session IS 'In-progress CSV imports (issue #263): parsed rows, match candidates and review decisions. 24 h TTL.';

COMMIT;

